// Writes the stylesheet's class names as typed exports, so a class name that
// styles.module.css doesn't define fails the typecheck.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

export const CSS_FILE = 'src/renderer/styles.module.css';
export const TYPES_FILE = 'src/renderer/styles.module.d.css.ts';

// The class names in the CSS's selectors, sorted.
export function classNames(css) {
  const names = new Set();
  for (const selector of css.replace(/\/\*[\s\S]*?\*\//g, '').split(/[{}]/).filter((_, i) => i % 2 === 0)) {
    if (selector.trimStart().startsWith('@')) {
      continue;
    }
    for (const match of selector.matchAll(/(?<![0-9])\.([a-zA-Z][a-zA-Z0-9]*)/g)) {
      names.add(match[1]);
    }
  }
  return [...names].sort();
}

export function cssTypes(css) {
  return [
    '// @generated by scripts/css-types.mjs from styles.module.css. Do not edit.',
    'declare const styles: {',
    ...classNames(css).map((name) => `  readonly ${name}: string;`),
    '};',
    'export default styles;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TYPES_FILE, cssTypes(readFileSync(CSS_FILE, 'utf8')));
}
